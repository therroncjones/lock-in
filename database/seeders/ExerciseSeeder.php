    /**
     * @return list<string>
     */
    public static function typesFor(string $name, ?string $group): array
    {
        $types = [];

        foreach (self::sessions() as $type => $names) {
            if (in_array($name, $names, true)) {
                $types[] = $type;
            }
        }

        foreach (match ($group) {
            'Upper Body' => ['Strength - Upper Body', 'Strength - Full Body'],
            'Lower Body' => ['Strength - Lower Body', 'Strength - Full Body'],
            'Core' => ['Strength - Upper Body', 'Strength - Lower Body', 'Strength - Full Body'],
            'Full Body' => ['Strength - Full Body'],
            default => [],
        } as $type) {
            $types[] = $type;
        }

        return array_values(array_unique($types));
    }
