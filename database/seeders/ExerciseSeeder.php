    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        foreach (self::library() as $group => $names) {
            foreach ($names as $name) {
                $exercise = Exercise::query()->firstOrNew([
                    'user_id' => null,
                    'name' => $name,
                ]);
                $exercise->group = $group;
                $exercise->measure = SetMeasure::forExerciseName($name);
                $exercise->session_types = self::typesFor($name, $group);

                if ($exercise->approved_at === null) {
                    $exercise->approved_at = now();
                }

                $exercise->save();
            }
        }
    }

